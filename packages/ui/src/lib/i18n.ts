const DICT: Record<Lang, Record<Key, string>> = { ar, en };

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function relTime(lang: Lang, ts: number, now = Date.now()): string {
  const d = Math.max(0, now - ts);
  const m = Math.floor(d / 60_000);
  if (m < 1) return t(lang, 'time.now');
  if (m < 60) return t(lang, 'time.min', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t(lang, 'time.hour', { n: h });
  return t(lang, 'time.day', { n: Math.floor(h / 24) });
}
